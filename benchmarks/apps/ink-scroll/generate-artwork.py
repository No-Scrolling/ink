from pathlib import Path
import random

from PIL import Image, ImageDraw


root = Path(__file__).parent
assets = root / "assets" / "artwork"
assets.mkdir(parents=True, exist_ok=True)
imports = []
entries = []

for row in range(500):
    if row % 8 not in (0, 1, 3, 6, 7):
        continue
    rng = random.Random(row)
    colours = [tuple(rng.randrange(40, 230) for _ in range(3)) for _ in range(3)]
    image = Image.new("RGB", (256, 256), colours[0])
    draw = ImageDraw.Draw(image)
    for y in range(256):
        colour = tuple(round(a + (b - a) * y / 255) for a, b in zip(colours[0], colours[1]))
        draw.line((0, y, 255, y), fill=colour)
    for _ in range(8):
        x, y = rng.randrange(-40, 220), rng.randrange(-40, 220)
        size = rng.randrange(30, 140)
        draw.ellipse((x, y, x + size, y + size), outline=colours[2], width=rng.randrange(2, 9))
    draw.rectangle((12, 200, 120, 244), fill="black")
    draw.text((20, 205), str(row + 1), fill="white", font_size=28)
    image.save(assets / f"{row}.jpg", quality=80)
    imports.append(f'import image{row} from "./assets/artwork/{row}.jpg";')
    entries.append(f"  {row}: image{row},")

(root / "artwork.ts").write_text(
    "// Generated by uv run benchmarks/apps/ink-scroll/generate-artwork.py.\n"
    + "\n".join(imports)
    + "\n\nexport const artwork: Partial<Record<number, string>> = {\n"
    + "\n".join(entries)
    + "\n};\n"
)
print(f"Generated {len(entries)} unique images for 500 mixed rows.")
